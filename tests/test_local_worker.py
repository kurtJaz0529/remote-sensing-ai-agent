import copy
import json
import sys
import time
import unittest
from pathlib import Path
from tempfile import TemporaryDirectory
from unittest.mock import patch
from contracts import canonical
from orchestrator.engine import Engine
from orchestrator.examples import mock_plan
from orchestrator.intake import inventory
from orchestrator.local_worker import LocalWorker
from orchestrator.worker import JsonWorker


class LocalWorkerTests(unittest.TestCase):
    def setUp(self):
        self.tmp = TemporaryDirectory(); self.addCleanup(self.tmp.cleanup)
        self.base = Path(self.tmp.name)
        inputs = self.base / 'inputs'; inputs.mkdir()
        (inputs / 'fixture.txt').write_text('synthetic fixture')
        self.engine = Engine(self.base / 'runtime'); self.addCleanup(self.engine.store.close)
        self.plan = mock_plan(inventory(inputs, 'synthetic'))
        self.engine.save_plan(self.plan, inventory(inputs, 'synthetic'), inputs)
        approval = self.engine.approve(self.plan['task_id'], 1, 'test-fixture')
        self.run = self.engine.create_run(self.plan['task_id'], 1, approval, 'mock')
        self.worker = LocalWorker(self.base / 'runtime'); self.addCleanup(self.worker.close)

    def dispatch_without_process(self):
        with patch('orchestrator.local_worker.subprocess.Popen'):
            status = self.engine.execute(self.run, self.worker)
        self.assertEqual(status['state'], 'Paused')
        row = self.engine.store.db.execute('SELECT body FROM steps WHERE run=?', (self.run,)).fetchone()
        return json.loads(row[0])

    def test_detached_process_and_resume(self):
        client = JsonWorker([sys.executable, '-m', 'orchestrator.local_worker', '--root', str(self.worker.root)])
        self.engine.execute(self.run, client)
        job = json.loads(self.engine.store.db.execute('SELECT body FROM steps WHERE run=?', (self.run,)).fetchone()[0])
        deadline = time.monotonic() + 15
        while client.status(job['job_id'])['status'] in ('queued', 'running') and time.monotonic() < deadline:
            time.sleep(.1)
        self.assertEqual(client.status(job['job_id'])['status'], 'succeeded')
        self.assertEqual(self.engine.execute(self.run, client)['state'], 'Completed')
        self.assertEqual(client.submit(job)['status'], 'succeeded')
        self.assertEqual(self.worker.db.execute('SELECT count(*) FROM jobs').fetchone()[0], 1)

    def test_changed_confirmation_rejected(self):
        job = self.dispatch_without_process()
        self.worker.db.execute('DELETE FROM jobs'); self.worker.db.commit()
        self.engine.store.db.execute('DELETE FROM approvals'); self.engine.store.db.commit()
        with self.assertRaises(ValueError): self.worker.submit(job)

    def test_same_key_changed_payload_rejected(self):
        job = self.dispatch_without_process()
        bad = copy.deepcopy(job); bad['parameters']['message'] = 'changed'
        with self.assertRaises(ValueError): self.worker.submit(bad)

    def test_cancel_queued_prevents_side_effect(self):
        job = self.dispatch_without_process()
        self.assertEqual(self.worker.cancel(job['job_id'])['status'], 'cancelled')
        self.worker.execute(job['job_id'])
        self.assertFalse((self.worker.root / 'runs' / self.run / 'artifacts/S1/mock.txt').exists())

    def test_stale_lock_never_taken_over(self):
        job = self.dispatch_without_process()
        with self.worker.db:
            self.worker.db.execute('INSERT INTO locks VALUES(?,?,?,?)', ('software:mock', 'old-job', 999999, '2000-01-01'))
        self.worker.execute(job['job_id'])
        self.assertEqual(self.worker.status(job['job_id'])['status'], 'failed')
        self.assertEqual(self.worker.db.execute('SELECT owner FROM locks').fetchone()[0], 'old-job')

    def test_timeout_no_output(self):
        # Trust records are generated by the coordinator, including the short timeout.
        self.plan['revision'] = 2
        self.plan['method_plan'][0]['timeout_seconds'] = .001
        row, _, manifest = self.engine._plan(self.plan['task_id'], 1)
        self.engine.save_plan(self.plan, manifest, row['input_root'])
        approval = self.engine.approve(self.plan['task_id'], 2, 'test-fixture')
        self.run = self.engine.create_run(self.plan['task_id'], 2, approval, 'mock')
        job = self.dispatch_without_process(); self.worker.execute(job['job_id'])
        self.assertEqual(self.worker.status(job['job_id'])['error']['code'], 'TIMEOUT')

    def test_unknown_job_never_recreated(self):
        with self.assertRaises(ValueError): self.worker.status('missing')
        self.assertEqual(self.worker.db.execute('SELECT count(*) FROM jobs').fetchone()[0], 0)

    def test_running_cancel_confirmed_by_runner(self):
        job = self.dispatch_without_process()
        def request_cancel(_):
            other = LocalWorker(self.worker.root)
            try:
                self.assertEqual(other.cancel(job['job_id'])['status'], 'running')
            finally:
                other.close()
        with patch('orchestrator.local_worker.time.sleep', side_effect=request_cancel):
            self.worker.execute(job['job_id'])
        self.assertEqual(self.worker.status(job['job_id'])['status'], 'cancelled')
        self.assertEqual(self.worker.db.execute('SELECT count(*) FROM locks').fetchone()[0], 0)

    def test_input_changed_between_enqueue_and_run(self):
        job = self.dispatch_without_process()
        (self.base / 'inputs/fixture.txt').write_text('changed after queue')
        self.worker.execute(job['job_id'])
        self.assertEqual(self.worker.status(job['job_id'])['status'], 'failed')
        self.assertFalse((self.worker.root / 'runs' / self.run / 'artifacts/S1/mock.txt').exists())

    def test_launch_failure_has_terminal_result(self):
        with patch('orchestrator.local_worker.subprocess.Popen', side_effect=OSError('test')):
            self.engine.execute(self.run, self.worker)
        job = json.loads(self.engine.store.db.execute('SELECT body FROM steps WHERE run=?', (self.run,)).fetchone()[0])
        self.assertEqual(self.worker.status(job['job_id'])['error']['code'], 'PROCESS_START_FAILED')

    def test_interrupted_running_job_not_replayed(self):
        job = self.dispatch_without_process()
        result = self.worker.status(job['job_id']); result['status'] = 'running'
        with self.worker.db:
            self.worker.db.execute('UPDATE jobs SET result=?', (canonical(result),))
        self.worker.execute(job['job_id'])
        self.assertEqual(self.worker.submit(job)['status'], 'running')
        self.assertFalse((self.worker.root / 'runs' / self.run / 'artifacts/S1/mock.txt').exists())
